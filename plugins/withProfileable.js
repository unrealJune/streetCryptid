const { withAndroidManifest } = require('@expo/config-plugins');

/**
 * Marks the Android app `<profileable android:shell="true"/>` on builds that carry developer
 * telemetry, so a release build installed on a real phone can be memory-profiled over adb
 * (`am dumpheap`, heapprofd / Perfetto native heap profiles) without being made debuggable.
 *
 * Why: on 2026-10-21 a Pixel's process reached 3.5 GB and was killed, and the build on it could
 * not be heap-dumped — the only evidence was a number in `exit-info`. A debuggable build changes
 * too much (no R8, JIT everywhere, different GC behaviour) to trust its heap; profileable changes
 * nothing about how the app runs, it only lets the shell user attach a profiler.
 *
 * Gated on `EXPO_PUBLIC_DEV_TELEMETRY`, the same switch as the OTEL pipeline, so stripping
 * developer telemetry from a profile (AGENTS.md) strips this with it. `android/` is regenerated by
 * `expo prebuild`, so the change is re-applied every prebuild (same pattern as withSharedSigning).
 */
module.exports = function withProfileable(config) {
  if (process.env.EXPO_PUBLIC_DEV_TELEMETRY !== '1') return config;
  return withAndroidManifest(config, (mod) => {
    const app = mod.modResults.manifest.application?.[0];
    if (!app) return mod;
    app.profileable = [{ $: { 'android:shell': 'true' } }];
    return mod;
  });
};
